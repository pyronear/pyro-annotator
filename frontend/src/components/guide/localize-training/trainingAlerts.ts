import type { NormalizedBox } from '@/utils/annotation/boxOverlap';

/**
 * The localization training set: four real alerts from the pinned sample
 * dataset (`.sample-data/sample-data-v1`, see annotation_api/docs/sample-data.md),
 * each a single wildfire object whose localization was validated.
 *
 * Every frame carries what the localize page would offer for it — the engine
 * and auto model boxes, exactly as the alert was imported — and `expected`,
 * the box the validated annotation kept (null: no smoke on that frame). Two
 * alerts are ones where the model got it right; on the other two it did not
 * (a box on a power line, boxes far too loose for the plume), which is the
 * point of the exercise.
 *
 * Generated by a one-off script from the manifest; frames are downscaled to
 * 1024px and live in frontend/public/guide/localization/<key>/. Alert 1051
 * keeps only frames 17-25: its earlier frames have validated answers that
 * are ambiguous on the image itself, which would mark a careful learner wrong.
 *
 * A prediction is `[x1, y1, x2, y2, confidence]`, normalized.
 */
export type TrainingPrediction = [number, number, number, number, number];

export interface TrainingFrame {
  src: string;
  recordedAt: string;
  engine: TrainingPrediction[];
  auto: TrainingPrediction[];
  expected: NormalizedBox | null;
}

export interface TrainingAlert {
  key: string;
  organisation: string;
  camera: string;
  recordedAt: string;
  /** What this alert teaches, shown once it has been submitted. */
  lesson: string;
  frames: TrainingFrame[];
}

